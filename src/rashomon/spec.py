"""Render the settled interpretation as a Markdown spec, plus a spec-kit compatible Clarifications block."""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

from rashomon import __version__
from rashomon.diff import behaviour_text, support
from rashomon.lenses import LENSES, letters
from rashomon.text import slug

OUTCOME_TEXT = {
    "converged": "converged",
    "max_rounds": "stopped at the round limit (not converged)",
    "nothing_to_ask": "no askable divergence left (not fully converged)",
    "predicted": "prediction only (no questions asked)",
    "error": "error",
}


def current_records(state: dict) -> list[dict]:
    return [p for p in state.get("plans", []) if p["round"] == state.get("round") and p.get("plan")]


def _majority(n: int) -> int:
    return n // 2 + 1


def _test_name(b: dict) -> str:
    return "test_" + slug(f"{b['when']} {b['then']}").replace("-", "_")[:60].rstrip("_")


def build_spec(state: dict) -> str:
    ticket = state["ticket"]
    records = current_records(state)
    n = len(records)
    analysis = state.get("analysis", {"divergences": [], "agreed": []})
    history = state.get("history", [])
    score = history[-1]["score"] if history else 0.0
    outcome = state.get("outcome", "converged")
    settled = state.get("settled", {})
    out: list[str] = [
        f"# Spec: {ticket.get('title', ticket.get('id', ''))}",
        "",
        f"> Ticket `{ticket.get('id', '')}`{' (' + ticket['url'] + ')' if ticket.get('url') else ''} · "
        f"{OUTCOME_TEXT.get(outcome, outcome)} · convergence **{score:.2f}** after {state.get('round', 0)} "
        f"round(s) · generated by rashomon {__version__}",
        "",
        "## Settled assumptions",
        "",
        "| Decision | Answer | Proposed by | How |",
        "| --- | --- | --- | --- |",
    ]
    rows = 0
    for d in settled.values():
        out.append(f"| {d['topic']} | {d['value']} | {letters(d.get('lenses', []))} | asked, round {d['round']} |")
        rows += 1
    for row in analysis.get("agreed", []):
        if row["dimension"] != "assumption" or any(row["topic"] == d["topic"] for d in settled.values()):
            continue
        g = row["groups"][0]
        how = "all lenses agreed" if len(g["lenses"]) == n else f"stated by {letters(g['lenses'])}, none disagreed"
        out.append(f"| {row['topic']} | {g['value']} | {letters(g['lenses'])} | {how} |")
        rows += 1
    if not rows:
        out.append("| (none) | | | |")

    open_rows = [d for d in analysis.get("divergences", []) if d["askable"]]
    if open_rows:
        out += ["", "## Still open", ""]
        for d in open_rows:
            split = "; ".join(f"{letters(g['lenses'])}: {g['value']}" for g in d["groups"])
            out.append(f"- **{d['topic']}** (impact {d['impact']}): {split}")

    behaviours = {behaviour_text(b): b for r in records for b in r["plan"]["behaviours"]}
    by_support = support(records, "behaviours")
    criteria = [(label, lenses) for label, lenses in by_support if len(lenses) >= _majority(n)]
    edge = [(label, lenses) for label, lenses in by_support if len(lenses) < _majority(n)]
    out += ["", "## Acceptance criteria", ""]
    out += [f"- [ ] {label}" for label, _ in criteria] or ["- (no behaviour reached a majority of lenses)"]
    if edge:
        out += ["", "### Edge cases raised by fewer lenses", ""]
        out += [f"- [ ] {label} ({letters(lenses)})" for label, lenses in edge]

    out += ["", "## Changes", "", "### Files", "", "| Path | Change | Lenses |", "| --- | --- | --- |"]
    changes = {f["path"]: f["change"] for r in records for f in r["plan"]["files"]}
    for path, lenses in support(records, "files"):
        out.append(f"| `{path}` | {changes.get(path, 'modify')} | {letters(lenses)} |")
    for dimension, title in (("api", "API"), ("schema", "Schema")):
        items = [(label, lenses) for label, lenses in support(records, dimension) if len(lenses) >= _majority(n)]
        out += ["", f"### {title}", ""]
        out += [f"- {label} ({letters(lenses)})" for label, lenses in items] or ["- none"]

    scope = [(label, lenses) for label, lenses in support(records, "out_of_scope") if len(lenses) >= 2]
    out += ["", "## Out of scope", ""]
    out += [f"- {label} ({letters(lenses)})" for label, lenses in scope] or ["- (nothing two lenses agreed on)"]

    out += ["", "## Test stubs", "", "```python", "import pytest"]
    for label, _ in criteria + edge:
        b = behaviours.get(label)
        if not b:
            continue
        out += [
            "",
            "",
            f"def {_test_name(b)}():",
            f'    """Given {b["given"]}.',
            f"    When {b['when']}.",
            f'    Then {b["then"]}."""',
            '    pytest.skip("not implemented")',
        ]
    out += ["```", "", "## How this was produced", ""]
    out.append(
        "Five independent plans (" + ", ".join(f"{lens.letter} {lens.name}" for lens in LENSES) + ") per round, "
        "diffed and scored by code. Convergence by round: "
        + ", ".join(f"{h['round']}: {h['score']:.2f}" for h in history)
        + "."
    )
    notes = state.get("notes", [])
    if notes:
        out += ["", f"Guard corrections ({len(notes)}):", ""]
        out += [f"- round {g['round']} {g['lens']}: `{g['code']}` {g['detail']}" for g in notes[:30]]
    return "\n".join(out).rstrip() + "\n"


def speckit_session(answered: list[dict], today: str | None = None) -> str:
    """The Q/A lines in the format ``/speckit.clarify`` writes, under a dated session heading."""
    today = today or date.today().isoformat()
    lines = [f"### Session {today}", ""]
    lines += [f"- Q: {a['question']} → A: {a['value']}" for a in answered]
    return "\n".join(lines) + "\n"


def apply_to_speckit(spec_path: Path, answered: list[dict], today: str | None = None) -> None:
    """Append a Clarifications session to a spec-kit ``spec.md`` (creates the section if missing)."""
    text = spec_path.read_text() if spec_path.exists() else ""
    block = speckit_session(answered, today)
    if re.search(r"^## Clarifications\s*$", text, re.MULTILINE):
        # insert right after the existing section's body, before the next ## heading
        m = re.search(r"^## Clarifications\s*$", text, re.MULTILINE)
        assert m is not None
        nxt = re.search(r"^## ", text[m.end() :], re.MULTILINE)
        cut = m.end() + (nxt.start() if nxt else len(text) - m.end())
        head, tail = text[:cut].rstrip() + "\n\n", text[cut:]
        text = head + block + ("\n" + tail if tail else "")
    else:
        text = (text.rstrip() + "\n\n" if text.strip() else "") + "## Clarifications\n\n" + block
    spec_path.write_text(text)
